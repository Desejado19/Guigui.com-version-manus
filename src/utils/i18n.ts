export function getTranslation(lang: Language, key: string, variables?: Record<string, string | number>): string {
  const locale = LANGUAGE_TO_LOCALE[lang];
  const raw = LOCALES[locale][key as keyof typeof LOCALES[typeof locale]]
    || TRANSLATIONS[lang]?.[key]
    || (key.startsWith('workspace.') ? getWorkspaceTranslation(lang, key.replace(/^workspace\./, '')) : undefined)
    || LOCALES.en[key as keyof typeof LOCALES.en]
    || TRANSLATIONS.en?.[key]
    || LOCALES['pt-BR'][key as keyof typeof LOCALES['pt-BR']]
    || TRANSLATIONS.pt?.[key]
    || key;
  return Object.entries(variables || {}).reduce(
    (text, [name, value]) => text.replace(new RegExp(`\\{\\{${name}\\}\\}`, 'g'), String(value)),
    raw,
  );
}

/**
 * Secção 11.5 — O Crioulo Guineense (Kriyol) faz parte das línguas oficiais da plataforma,
 * pelo que o ciclo de troca de idioma tem de o incluir em todos os painéis.
 */
export const LANGUAGE_CYCLE: readonly Language[] = ['pt', 'en', 'fr', 'es'] as const;

export function getLanguageLabelCurrent(lang: Language, currentLang: Language): string {
  if (lang === currentLang) {
    return getTranslation(currentLang, `language.${lang}`);
  }
  return `${getTranslation(currentLang, `language.${lang}`)} · ${getTranslation(lang, `language.${lang}`)}`;
}


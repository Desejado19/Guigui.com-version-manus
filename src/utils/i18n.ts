/** Sigla curta apresentada no botão de troca de idioma. */
export function getLanguageShortLabel(lang: Language): string {
  return String(lang).toUpperCase();
}

/** Próxima língua do ciclo, usada pelos botões que alternam o idioma. */
export function getNextLanguage(lang: Language): Language {
  const index = LANGUAGE_CYCLE.indexOf(lang);
  return LANGUAGE_CYCLE[(index + 1) % LANGUAGE_CYCLE.length];
}

export function resolveLanguage(value: unknown, fallback: Language = 'pt'): Language {
  if (value === 'pt' || value === 'en' || value === 'fr' || value === 'es') return value;
  if (typeof value === 'string') {
    const base = value.toLowerCase().split(/[-_]/)[0];
    if (base === 'pt' || base === 'en' || base === 'fr' || base === 'es') return base;
  }
  return fallback;
}

export function detectLanguage(): Language {
  if (typeof window === 'undefined') return 'pt';
  const stored = window.localStorage.getItem('guigui_current_lang');
  if (stored) {
    try {
      return resolveLanguage(JSON.parse(stored));
    } catch {
      return resolveLanguage(stored);
    }
  }
  return resolveLanguage(window.navigator.language, 'pt');
}

export function translateCount(lang: Language, key: string, count: number): string {
  const suffix = Math.abs(count) === 1 ? '' : '_plural';
  return getTranslation(lang, `${key}${suffix}`, { count });
}

export function formatNumber(value: number, lang: Language): string {
  return new Intl.NumberFormat(LANGUAGE_TO_LOCALE[lang]).format(value);
}

export function formatPercent(value: number, lang: Language): string {
  return new Intl.NumberFormat(LANGUAGE_TO_LOCALE[lang], { style: 'percent', maximumFractionDigits: 2 }).format(value);
}

export function formatCurrency(value: number, lang: Language, currency = 'XOF'): string {
  return new Intl.NumberFormat(LANGUAGE_TO_LOCALE[lang], { style: 'currency', currency }).format(value);
}

export function formatDateTime(value: string | number | Date, lang: Language): string {
  return new Intl.DateTimeFormat(LANGUAGE_TO_LOCALE[lang], { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(value));
}

export function formatCurrencyXOF(value: number, lang: Language): string {
  return `${formatNumber(value, lang)} ${getTranslation(lang, 'currencyXof')}`;
}

export function formatDate(value: string | number | Date, lang: Language, options?: Intl.DateTimeFormatOptions): string {
  return new Intl.DateTimeFormat(LANGUAGE_TO_LOCALE[lang], options).format(new Date(value));
}


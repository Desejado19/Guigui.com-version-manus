export function resolveRequestLanguage(header: unknown): Language {
  const value = typeof header === 'string' ? header.toLowerCase() : '';
  const requested = value.split(',')[0].split('-')[0];
  return requested === 'en' || requested === 'fr' || requested === 'es' ? requested : 'pt';
}

export function localizeApiPayload(payload: unknown, language: Language): unknown {
  if (!payload || typeof payload !== 'object' || Array.isArray(payload)) return payload;
  const record = payload as Record<string, unknown>;
  const code = typeof record.code === 'string' ? record.code : undefined;
  const message = code ? MESSAGES[language][code] : undefined;
  return message ? { ...record, message, error: record.error ? message : record.error } : payload;
}
